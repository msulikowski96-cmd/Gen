import express from "express";
import path from "path";
import { createServer as createViteServer } from "vite";
import satori from 'satori';
import { Resvg } from '@resvg/resvg-js';
import fs from 'fs';

const USE_MOCK_DATA = true;

async function getPlayerData(summonerName: string) {
    if (USE_MOCK_DATA) {
        return {
            name: summonerName,
            level: 245,
            rank: 'Diamond IV',
            winRate: '54.2%',
            color: '#3b82f6' // tailwind blue-500
        };
    }
    return { name: summonerName, rank: 'Unknown', winRate: '0%', color: '#ccc' };
}

async function getFontData() {
    const fontPath = path.join(process.cwd(), 'font.ttf');
    if (fs.existsSync(fontPath)) {
        return fs.readFileSync(fontPath);
    }
    
    let ttfUrl = 'https://fonts.gstatic.com/s/inter/v20/UcCO3FwrK3iLTeHuS_nVMrMxCp50SjIw2boKoduKmMEVuLyfAZ9hjZ-Ck-8.ttf';
    try {
        const cssRes = await fetch("https://fonts.googleapis.com/css?family=Inter", {
            headers: {
                "User-Agent": "Mozilla/5.0 (Linux; U; Android 4.1.1; en-gb; Build/KLP) AppleWebKit/534.30 (KHTML, like Gecko) Version/4.0 Safari/534.30"
            }
        });
        const css = await cssRes.text();
        const match = css.match(/url\((https:\/\/[^)]+\.ttf)\)/);
        if (match) {
            ttfUrl = match[1];
        }
    } catch (e) {
        console.error('Failed to fetch Google Fonts CSS, using fallback font url.', e);
    }

    const response = await fetch(ttfUrl);
    if (!response.ok) {
        throw new Error('Failed to download font TTF: ' + response.statusText);
    }
    const arrayBuffer = await response.arrayBuffer();
    const buffer = Buffer.from(arrayBuffer);
    fs.writeFileSync(fontPath, buffer);
    return buffer;
}

async function startServer() {
  const app = express();
  const PORT = 3000;
  
  app.use(express.json());

  // API routes FIRST
  app.get("/api/health", (req, res) => {
    res.json({ status: "ok" });
  });

  app.post('/api/generate', async (req, res) => {
    try {
        const { nickname } = req.body;
        const data = await getPlayerData(nickname || 'Unknown');
        const fontData = await getFontData();

        const svg = await satori(
            {
                type: 'div',
                props: {
                    style: {
                        display: 'flex', flexDirection: 'column', backgroundColor: '#1a1a2e',
                        color: 'white', width: '400px', height: '600px', padding: '40px',
                        borderRadius: '20px', fontFamily: 'Inter', border: `10px solid ${data.color}`,
                    },
                    children: [
                        { type: 'div', props: { style: { fontSize: '40px', fontWeight: 'bold', marginBottom: '20px', textAlign: 'center' }, children: data.name } },
                        { type: 'div', props: { style: { display: 'flex', justifyContent: 'space-between', fontSize: '24px', marginBottom: '10px' }, children: [{ type: 'span', props: { children: 'Rank: ' } }, { type: 'span', props: { style: { fontWeight: 'bold' }, children: data.rank } }] } },
                        { type: 'div', props: { style: { display: 'flex', justifyContent: 'space-between', fontSize: '24px', marginBottom: '10px' }, children: [{ type: 'span', props: { children: 'Win Rate: ' } }, { type: 'span', props: { style: { fontWeight: 'bold' }, children: data.winRate } }] } },
                        { type: 'div', props: { style: { marginTop: '40px', fontSize: '20px', textAlign: 'center', opacity: 0.7 }, children: 'Generated by Nexus-Sight.pl'} },
                    ],
                },
            },
            { 
              width: 400, 
              height: 600, 
              fonts: [{ name: 'Inter', data: fontData, weight: 400, style: 'normal' }] 
            }
        );

        const resvg = new Resvg(svg);
        const pngBuffer = resvg.render().asPng();
        res.set('Content-Type', 'image/png').send(pngBuffer);
    } catch (error) {
        console.error(error);
        res.status(500).send('Error generating card');
    }
  });

  // Vite middleware for development
  if (process.env.NODE_ENV !== "production") {
    const vite = await createViteServer({
      server: { middlewareMode: true },
      appType: "spa",
    });
    app.use(vite.middlewares);
  } else {
    const distPath = path.join(process.cwd(), 'dist');
    app.use(express.static(distPath));
    app.get('*', (req, res) => {
      res.sendFile(path.join(distPath, 'index.html'));
    });
  }

  app.listen(PORT, "0.0.0.0", () => {
    console.log(`Server running on http://localhost:${PORT}`);
  });
}

startServer();
